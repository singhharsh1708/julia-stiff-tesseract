# Generate plain Julia from the ModelingToolkit model, so the Tesseract does not load ModelingToolkit at run time.
#
#   julia --project=tools tools/generate.jl
#
# Writes lindauer/julia/src/generated/lindauer_params.jl (the plain-Julia part of the model file: constants, parameter
# sets, `derive`) and lindauer/julia/src/generated/lindauer_rhs.jl (right-hand side and Jacobian of the compiled system,
# in place, with the state and parameter order). Rerun whenever lindauer/julia/src/lindauer_model.jl changes.
using ModelingToolkit

const SRC = joinpath(@__DIR__, "..", "lindauer", "julia", "src")
const OUT = joinpath(SRC, "generated")
mkpath(OUT)
model_file = joinpath(SRC, "lindauer_model.jl")
include(model_file)

header = "# Generated by tools/generate.jl from lindauer/julia/src/lindauer_model.jl. Do not edit.\n"

# 1. Plain-Julia part: everything before the symbolic declarations, minus the ModelingToolkit imports.
lines = readlines(model_file)
stop = findfirst(l -> startswith(l, "@parameters"), lines)
keep = filter(l -> !startswith(l, "using ModelingToolkit"), lines[1:(stop - 1)])
write(joinpath(OUT, "lindauer_params.jl"), header * join(keep, "\n") * "\n")

# 2. Right-hand side and Jacobian of the compiled system, with a plain parameter vector (split = false).
# guard = true: the drug effect is linear in RO below 0.01 %, as in the paper's NONMEM control stream (s006).
# Without it, RO^gamma with gamma < 1 (the Fig 4 gamma x0.2 bars) has an infinite slope at RO = 0, where every
# dose segment starts, and Rodas5P fails; with it the results equal QSPAtlas's to 1e-9 (tools/test.jl).
compiled = build_lindauer(guard = true)
full = System(vcat(equations(compiled), observed(compiled)), t; name = :lindauer)
sys = mtkcompile(full; split = false)
_, rhs_iip = ModelingToolkit.generate_rhs(sys; expression = Val{true})
_, jac_iip = ModelingToolkit.generate_jacobian(sys; expression = Val{true})
names(v) = [Symbol(replace(string(x), "(t)" => "")) for x in v]
open(joinpath(OUT, "lindauer_rhs.jl"), "w") do io
    write(io, header)
    println(io, "const UNKNOWNS = ", repr(names(unknowns(sys))))
    println(io, "const PARAMETERS = ", repr(names(parameters(sys))))
    # SymbolicUtils' type-widening helper, copied so the generated code needs no symbolic packages at run time.
    println(io, "_widen_float(x::AbstractFloat, other::Real) = promote_type(typeof(x), typeof(other)) === typeof(other) ? convert(typeof(other), x) : x")
    println(io, "_widen_float(x, other) = x")
    local_code(ex) = replace(string(ex), "(SymbolicUtils.Code.widen_float)" => "(_widen_float)")
    println(io, "const lindauer_rhs! = ", local_code(rhs_iip))
    println(io, "const lindauer_jac! = ", local_code(jac_iip))
end
println("wrote ", OUT, ": ", length(unknowns(sys)), " states, ", length(parameters(sys)), " parameters")
